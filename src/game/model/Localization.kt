    fun langCode(lang: String): String {
        val lower = lang.lowercase().trim()
        return when {
            lower.startsWith("pt") -> PT_BR
            lower.startsWith("zh") -> ZH_TW
            lower.startsWith("fr") -> FR
            lower.startsWith("es") -> ES
            lower.startsWith("de") -> DE
            lower.startsWith("id") -> ID
            lower.startsWith("tr") -> TR
            lower.startsWith("vi") -> VI
            lower.startsWith("ru") -> RU
            lower.startsWith("ja") -> JA
            lower.startsWith("ko") -> KO
            lower.startsWith("hi") -> HI
            lower.startsWith("ar") -> AR
            lower.startsWith("th") -> TH
            else -> EN
        }
    }

    fun isFrench(lang: String): Boolean = langCode(lang) == FR

