fun TutorialStep.localizedCallout(lang: String): String {
    val translated = Localization.tutorialCallout(id, lang)
    if (!translated.isNullOrEmpty()) return translated
    val translatedTitle = Localization.tutorialTitle(id, lang)
    if (!translatedTitle.isNullOrEmpty() && handwrittenCallout == null) return translatedTitle
    return handwrittenCallout ?: title
}

fun TutorialStep.localizedTitle(lang: String): String {
    val translated = Localization.tutorialTitle(id, lang)
    return if (!translated.isNullOrEmpty()) translated else title
}

