"""
Measure where the guard's weight is in every walk frame, and write src/game/model/GuardWalkStance.kt.

Usage:  python tools/art/prep_guard_stance.py

Why: "guards moving looks like they are floating" (2026-10-26, level 11). A guard steps up onto a
lift's 14-unit deck (GameWorld.walkGuardOverDecks), and the walk frames are drawn on flat ground:
whichever height the body is drawn at, a boot on the other side of the deck's edge is drawn 14
inside the deck or 14 over the floor. Switching the height when his CENTRE crossed the edge left
the standing boot off its surface for most of a stride either side. What the eye reads as where
he stands is the boot carrying his weight - so the body goes to the height under that.

Per frame this takes the soles touching the ground (opaque in the bottom CONTACT_ROWS rows) and
their median column: during single support that is the planted boot, during double support the
middle of the two - against a single edge, the surface under the median sole pixel is the surface
under most of the sole. Written as a fraction of the standing silhouette height ahead of the body
centre (frames face right; the crop is symmetric about the body, so the centre is the middle
column), so GameWorld scales it by the guard's height and flips it with his facing.

Re-run after re-cutting the walk clip (prep_guard.py).
"""
import os

import numpy as np
from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..'))
FRAMES_DIR = os.path.join(ROOT, 'art', 'frames', 'guard', 'walk')
OUT = os.path.join(ROOT, 'src', 'game', 'model', 'GuardWalkStance.kt')

WALK_FRAMES = 38                 # GuardAnimations.WALK_FRAMES
SILHOUETTE = 244.0               # GuardAnimations.SOURCE_SILHOUETTE_HEIGHT
CONTACT_ROWS = 3


def measure():
    out = []
    for f in range(1, WALK_FRAMES + 1):
        a = np.array(Image.open(os.path.join(FRAMES_DIR, '%04d.png' % f)).convert('RGBA'))[:, :, 3] > 128
        h, w = a.shape
        cols = np.nonzero(a[h - CONTACT_ROWS:].any(0))[0]
        out.append((float(np.median(cols)) - w / 2.0) / SILHOUETTE)
    return out


def write(values):
    body = ',\n'.join('        ' + ', '.join('%.4f' % v for v in values[i:i + 8]) for i in range(0, len(values), 8))
    src = '''package game.model

// GENERATED by tools/art/prep_guard_stance.py - do not edit by hand; re-run it after re-cutting the
// guard's walk clip.

/**
 * Where the guard's weight is in each walk frame ([Guard.walkPhase] * [FRAMES]): the median column
 * of the soles touching the ground, ahead of the body's centre, as a fraction of his standing
 * height (frames face right). GameWorld.walkGuardOverDecks stands him on whatever is under it, so
 * the boot carrying him is on its surface as he steps onto and off a lift's deck - see the script.
 */
object GuardWalkStance {
    const val FRAMES = %d

    private val AHEAD = doubleArrayOf(
%s
    )

    /** The weight's distance ahead of the body's centre at walk frame [frame], per unit of height. */
    fun ahead(frame: Int): Double = AHEAD[frame.coerceIn(0, FRAMES - 1)]
}
''' % (len(values), body)
    open(OUT, 'w', encoding='utf-8', newline='\n').write(src)


if __name__ == '__main__':
    v = measure()
    write(v)
    print('wrote', OUT)
    print(' '.join('%.3f' % x for x in v))
